def test_universe_is_loaded_once_for_the_whole_batch(tmp_path, monkeypatch):
    """The point of the task: N strategies must NOT mean N cache/DuckDB reads.
    Counts `common.cli_utils.load_universe` (what `load_universe_with_banner`
    calls) across a 3-strategy serial batch."""
