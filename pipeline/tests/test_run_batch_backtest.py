# 8. The synthetic-provider caveat, documented rather than hidden
# --------------------------------------------------------------------------- #
def test_synthetic_provider_caveat_differing_warmups_share_a_wider_load(tmp_path):
    """`SyntheticDataProvider` builds a GBM path that starts at the REQUESTED
    start date, so its bars are NOT date-addressed. When one batch holds
    strategies with different warmups, the single shared load necessarily uses
    the widest window (`load_start` = the smallest fetch start) and every
    strategy sees that one path -- so a strategy that would have been loaded
    from a later start does not reproduce its standalone run's PRICES.

    What must still hold (and is asserted here): identical fold BOUNDARIES. The
    walk-forward window arithmetic is strategy-local and unaffected by the wider
    load, which is why the discrepancy is confined to the provider's generated
    values and disappears entirely for date-addressed providers (test 3) and for
    single-strategy batches (test 2).
    """
    universe_file = _write_universe_file(tmp_path)
    shared = _write_strategy(tmp_path, "eq_w5", "equal_weight", {"rebalance_freq_days": 5}, "EQ-W5")
    wide = _write_strategy(tmp_path, "iv20", "inverse_volatility",
                           {"vol_lookback": 20, "rebalance_freq_days": 21}, "IV-20")
    batch_out = os.path.join(str(tmp_path), "batch_out")
    direct_out = os.path.join(str(tmp_path), "direct_eq_w5")

    batch_run = _run_batch(universe_file, batch_out, [shared, wide])
    assert batch_run.returncode == 0, batch_run.stderr + batch_run.stdout
    direct_run = _run_direct(universe_file, direct_out, shared)
    assert direct_run.returncode == 0, direct_run.stderr + direct_run.stdout

    batch_folds = pd.read_csv(os.path.join(batch_out, "eq_w5", "walkforward_report.csv"))
    direct_folds = pd.read_csv(os.path.join(direct_out, "walkforward_report.csv"))
    assert list(batch_folds["start_date"]) == list(direct_folds["start_date"])
    assert list(batch_folds["end_date"]) == list(direct_folds["end_date"])
    # Prices differ -> the metrics differ. Asserted, not glossed over.
    assert not batch_folds.equals(direct_folds)


