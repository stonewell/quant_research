def test_failed_strategies_do_not_abort_the_batch(tmp_path):
    """Two probe-time failures (malformed JSON, unknown template) plus one good
    strategy: the good one must still run, the batch must exit 0, and each
    failure must be reported with its own exception text -- never swallowed."""
    universe_file = _write_universe_file(tmp_path)
    good = _write_strategy(tmp_path, "good", "equal_weight", {"rebalance_freq_days": 21}, "GOOD")
    bad_json = os.path.join(str(tmp_path), "bad_json.json")
    with open(bad_json, "w", encoding="utf-8") as handle:
        handle.write("{ not json")
    bad_template = _write_strategy(tmp_path, "bad_template", "nope_not_a_template", {})

    out = os.path.join(str(tmp_path), "out")
    run = _run_batch(universe_file, out, [bad_json, bad_template, good])
    assert run.returncode == 0, run.stderr + run.stdout

    assert os.path.exists(os.path.join(out, "good", "walkforward_summary.json"))
    failed = pd.read_csv(os.path.join(out, "batch_failed.csv"))
    assert list(failed.columns) == batch.FAILED_COLUMNS
    assert sorted(failed["strategy"]) == ["bad_json", "bad_template"]
    assert "JSONDecodeError" in failed.set_index("strategy").loc["bad_json", "error"]
    assert "nope_not_a_template" in failed.set_index("strategy").loc["bad_template", "error"]

    with open(os.path.join(out, "batch_summary.json"), "r", encoding="utf-8") as handle:
        summary = json.load(handle)
    assert summary["n_ok"] == 1 and summary["n_failed"] == 2

    ranking = pd.read_csv(os.path.join(out, "batch_ranking.csv"))
    assert list(ranking.columns) == batch.RANKING_COLUMNS
    assert ranking.set_index("strategy").loc["GOOD", "status"] == "ok"
    # Failures are unranked, never "ranked last" -- a reader must be able to
    # tell "no data" from "worst performer".
    assert pd.isna(ranking.set_index("strategy").loc["bad_json", "rank"])


def test_worker_level_failure_is_isolated_and_logged(tmp_path):
    """A strategy that passes the probe but explodes inside `run_walkforward`
    (window larger than the data) must be captured per strategy, not abort the
    batch: exit 0, every strategy failed, message in batch_failed.csv, full
    traceback in each strategy's run.log."""
    universe_file = _write_universe_file(tmp_path)
    strategies = [
        _write_strategy(tmp_path, "eq_w5", "equal_weight", {"rebalance_freq_days": 5}),
        _write_strategy(tmp_path, "eq_w21", "equal_weight", {"rebalance_freq_days": 21}),
    ]
    out = os.path.join(str(tmp_path), "out")
    run = _run_batch(universe_file, out, strategies, extra=["--window-years", "10"])
    assert run.returncode == 0, run.stderr + run.stdout

    for stem in ("eq_w5", "eq_w21"):
        assert not os.path.exists(os.path.join(out, stem, "walkforward_summary.json"))
        with open(os.path.join(out, stem, "run.log"), "r", encoding="utf-8") as handle:
            log = handle.read()
        assert "Window size is larger than the available data" in log
        assert "Traceback" in log
    failed = pd.read_csv(os.path.join(out, "batch_failed.csv"))
    assert len(failed) == 2
    assert failed["error"].str.contains("Window size is larger").all()


