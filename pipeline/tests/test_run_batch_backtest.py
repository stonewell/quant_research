"""`B2.3` -- batch walk-forward entry point (`scripts/run_batch_backtest.py`).

The whole task is "one interpreter, one universe load, N strategies", so the
tests are written as proofs rather than smoke tests:

1. **Bit-for-bit parity with the direct CLI.** A batch run of a single strategy
   must produce the same `walkforward_report.csv` / `walkforward_rebalances.csv`
   / `walkforward_summary.json` as `python backtester/run_backtest.py ...`
   byte for byte (subprocess vs subprocess, `--data-provider synthetic`).
2. **Multi-strategy parity for a date-addressed provider.** With several
   strategies whose warmup windows DIFFER, the one shared load + per-strategy
   trim must still reproduce each strategy's own independent run byte for byte.
   The provider for this test is `csv` over files generated by
   `common.testing.make_ar1_ohlcv` -- date-addressed exactly like the DuckDB
   cache / fuyao, and 100% offline.
3. **The `synthetic` provider caveat, stated as a test** (never masked): its GBM
   path starts at the REQUESTED start, so a strategy with a smaller warmup sees
   different prices when it shares a wider load. Fold boundaries stay identical
   -- only the generated prices differ -- which is why the batch's own offline
   default still ships `synthetic` for single-strategy/single-warmup runs.
4. **One universe load for the whole batch** (counted, in-process).
5. **`--n-jobs` changes nothing but the wall clock**, and the pool is really used.
6. **Failure isolation**: a broken strategy never aborts the batch; probe-time
   failures and worker-time failures are both reported in `batch_failed.csv`
   with their exception text (and the traceback in `run.log`).

Everything here is offline: synthetic data (`common/testing`) or the `csv`
provider over those same synthetic frames, always with `--no-cache`, and never
a real market provider.
"""

