def _write_strategy(directory, name, template_name, params, strategy_name=None):
    body = {"template_name": template_name, "params": params}
    if strategy_name:
        body["strategy_name"] = strategy_name
    path = os.path.join(str(directory), f"{name}.json")
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(body, handle, indent=2)
    return path


def _write_universe_file(tmp_path):
    path = os.path.join(str(tmp_path), "universe.txt")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(SYMBOLS) + "\n")
    return path


def _write_csv_data_dir(tmp_path):
    """4 symbols of deterministic synthetic OHLCV on disk, date-addressed --
    the same semantics as the real OHLCV cache (a wider request returns a
    superset of the same bars), which is what makes multi-strategy parity
    testable without touching the production cache."""
    directory = os.path.join(str(tmp_path), "csv_data")
    os.makedirs(directory, exist_ok=True)
    for index, symbol in enumerate(SYMBOLS):
        closes = make_ar1_ohlcv(phi=0.05, n=520, seed=100 + index, start="2020-09-01")["Close"]
        frame = make_ohlcv_from_closes(closes, spread=0.25, start="2020-09-01")
        frame["Volume"] = 1_000_000.0 + index
        frame.index.name = "Date"
        frame.to_csv(os.path.join(directory, f"{symbol}.csv"))
    return directory


def _common_cli(universe_file, extra):
    """The flags shared by the batch entry point and a direct run_backtest call."""
    return [
        "--universe-file", universe_file,
        "--start", START,
        "--end", END,
        "--window-years", WINDOW_YEARS,
        "--step-years", STEP_YEARS,
        "--no-cache",
        "--n-jobs", "1",
        *extra,
    ]


def _run_batch(universe_file, output_dir, strategies, extra=(), data=("--data-provider", "synthetic")):
    cmd = [
        sys.executable, BATCH_SCRIPT,
        "--strategies", *strategies,
        "--output-dir", output_dir,
        *data,
        *_common_cli(universe_file, []),
        *extra,
    ]
    return subprocess.run(cmd, cwd=_PROJECT_ROOT, capture_output=True, text=True)


def _run_direct(universe_file, results_dir, strategy_file, extra=(), data=("--data-provider", "synthetic")):
    cmd = [
        sys.executable, BACKTEST_SCRIPT,
        "--strategy-file", strategy_file,
        "--mode", "walkforward",
        "--results-dir", results_dir,
        *data,
        *_common_cli(universe_file, []),
        *extra,
    ]
    return subprocess.run(cmd, cwd=_PROJECT_ROOT, capture_output=True, text=True)


def _read_bytes(path):
    with open(path, "rb") as handle:
        return handle.read()


def _assert_same_artifacts(left_dir, right_dir, names=("walkforward_report.csv",
                                                       "walkforward_rebalances.csv",
                                                       "walkforward_summary.json")):
    for name in names:
        left, right = os.path.join(left_dir, name), os.path.join(right_dir, name)
        assert os.path.exists(left), f"missing {left}"
        assert os.path.exists(right), f"missing {right}"
        assert _read_bytes(left) == _read_bytes(right), f"{name} differs between {left_dir} and {right_dir}"


