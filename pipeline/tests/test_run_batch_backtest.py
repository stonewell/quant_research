# --------------------------------------------------------------------------- #
@pytest.mark.skipif(
    "fork" not in __import__("multiprocessing").get_all_start_methods(),
    reason="strategy-level batch parallelism requires the fork start method",
)
def test_parallel_batch_matches_serial_batch(tmp_path):
    universe_file = _write_universe_file(tmp_path)
    data_dir = _write_csv_data_dir(tmp_path)
    strategies = [
        _write_strategy(tmp_path, "eq_w5", "equal_weight", {"rebalance_freq_days": 5}, "EQ-W5"),
        _write_strategy(tmp_path, "eq_w21", "equal_weight", {"rebalance_freq_days": 21}, "EQ-W21"),
        _write_strategy(tmp_path, "iv20", "inverse_volatility",
                        {"vol_lookback": 20, "rebalance_freq_days": 21}, "IV-20"),
    ]
    data = ("--data-provider", "csv", "--data-dir", data_dir)
    serial_out = os.path.join(str(tmp_path), "serial_out")
    parallel_out = os.path.join(str(tmp_path), "parallel_out")

    serial = _run_batch(universe_file, serial_out, strategies, data=data)
    assert serial.returncode == 0, serial.stderr + serial.stdout
    parallel = _run_batch(universe_file, parallel_out, strategies,
                          extra=["--n-jobs", "3"], data=data)
    assert parallel.returncode == 0, parallel.stderr + parallel.stdout
    # Not a silent serial fallback: the pool really produced these numbers.
    assert "Parallel batch: dispatching 3 strategies to 3 worker process(es)" in parallel.stdout
    assert "falling back to the serial" not in parallel.stdout

    for strategy in strategies:
        stem = os.path.splitext(os.path.basename(strategy))[0]
        _assert_same_artifacts(os.path.join(serial_out, stem), os.path.join(parallel_out, stem))

    # Ranking matrix: identical except for the timing columns/paths.
    serial_rank = pd.read_csv(os.path.join(serial_out, "batch_ranking.csv"))
    parallel_rank = pd.read_csv(os.path.join(parallel_out, "batch_ranking.csv"))
    ignored = ["elapsed_seconds", "strategy_file"]
    pd.testing.assert_frame_equal(
        serial_rank.drop(columns=ignored), parallel_rank.drop(columns=ignored), check_exact=True
    )


